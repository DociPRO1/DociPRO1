/**
 * README composer.
 *
 * Each plate is emitted as two <picture> elements: one for the wide layout
 * and one for the compact layout. Theme and width are deliberately kept in
 * separate <source> elements, for this reason:
 *
 * GitHub wraps README pictures in <themed-picture>. When a user has forced a
 * light or dark theme (instead of "sync with system"), that element replaces
 * the ENTIRE media attribute of any <source> whose query mentions
 * prefers-color-scheme. A combined "(prefers-color-scheme: light) and
 * (max-width: 767px)" would lose its width condition. Sources that do not
 * mention prefers-color-scheme are left alone.
 *
 * So width is resolved first by a theme-free source that swaps the inactive
 * layout for a 1px spacer, and theme is resolved by plain prefers-color-scheme
 * sources. This holds in auto, forced-light and forced-dark modes, and without
 * <picture> support only the wide dark plate shows (no duplicates).
 */
import { BREAKPOINT } from './engine/theme.ts';
import { esc } from './engine/svg.ts';

export const SPACER = 'assets/spacer.svg';

export const asset = (id: string, layout: 'wide' | 'compact', theme: 'dark' | 'light') => `assets/${id}.${layout}.${theme}.svg`;

export function plate(id: string, alt: string, href?: string): string {
  const wide =
    `<picture>` +
    `<source media="(max-width: ${BREAKPOINT - 0.02}px)" srcset="${SPACER}">` +
    `<source media="(prefers-color-scheme: light)" srcset="${asset(id, 'wide', 'light')}">` +
    `<source media="(prefers-color-scheme: dark)" srcset="${asset(id, 'wide', 'dark')}">` +
    `<img src="${asset(id, 'wide', 'dark')}" width="100%" alt="${esc(alt)}">` +
    `</picture>`;
  const compact =
    `<picture>` +
    `<source media="(min-width: ${BREAKPOINT}px)" srcset="${SPACER}">` +
    `<source media="(prefers-color-scheme: light)" srcset="${asset(id, 'compact', 'light')}">` +
    `<source media="(prefers-color-scheme: dark)" srcset="${asset(id, 'compact', 'dark')}">` +
    `<img src="${SPACER}" width="100%" alt="">` +
    `</picture>`;
  // A <div> makes this a raw HTML block. Inside a Markdown paragraph, GitHub
  // wraps each <img> in a link to the file, which detaches it from <picture>
  // and silently disables every <source>.
  const body = `${wide}${compact}`;
  return `<div>${href ? `<a href="${esc(href)}">${body}</a>` : body}</div>`;
}

export interface ReadmeParts {
  plates: { id: string; alt: string; href?: string }[];
  /** Plain-text links rendered under the final plate (real, clickable, selectable). */
  links: { label: string; url: string }[];
  /** Hidden-from-layout text summary for search engines and screen readers. */
  summary: string;
}

export function composeReadme(p: ReadmeParts): string {
  const out: string[] = [];
  out.push('<!-- Generated by the profile engine (npm run build). Edit profile.config.ts, not this file. -->');
  out.push('');
  for (const pl of p.plates) {
    out.push(plate(pl.id, pl.alt, pl.href));
    out.push('');
  }
  if (p.links.length) {
    out.push(`<p>${p.links.map((l) => `<a href="${esc(l.url)}">${esc(l.label)}</a>`).join(' &nbsp;·&nbsp; ')}</p>`);
    out.push('');
  }
  out.push(`<!-- ${p.summary.replace(/--/g, '-')} -->`);
  out.push('');
  return out.join('\n');
}
